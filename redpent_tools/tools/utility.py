"""UTILITY lane — scope checks, asset merging, session notes, SOP §4.3 report."""
from __future__ import annotations

import json
from typing import Any

from ..context import ReconContext
from . import utils


def scope_check(ctx: ReconContext, target: str) -> dict[str, Any]:
    d = ctx.guard.decide(target)
    ctx.auditor.record("scope_check", {"target": target}, target,
                       "ok", note=f"in_scope={d.in_scope}")
    return {"ok": True, "in_scope": d.in_scope, "reason": d.reason,
            "resolved_ips": d.resolved_ips, "cdn": d.cdn}


def get_scope(ctx: ReconContext) -> dict[str, Any]:
    s = ctx.config.scope
    return {
        "configured": s.configured,
        "engagement_id": s.engagement_id, "roe_reference": s.roe_reference,
        "tester": s.tester, "in_scope_domains": s.in_scope_domains,
        "in_scope_cidrs": s.in_scope_cidrs, "out_of_scope": s.out_of_scope,
        "active_allowed": s.active_allowed, "active_window": s.active_window,
        "limits": {"masscan_max_rate": s.limits.masscan_max_rate,
                   "ffuf_max_threads": s.limits.ffuf_max_threads,
                   "nmap_max_timing": s.limits.nmap_max_timing},
        "allow_intrusive_nse": s.allow_intrusive_nse,
        "evidence_dir": str(ctx.config.evidence_dir),
        # secrets intentionally omitted
        "shodan_configured": bool(ctx.config.shodan_api_key),
        "censys_configured": bool(ctx.config.censys_api_id and ctx.config.censys_api_secret),
    }


def merge_assets(ctx: ReconContext, lists: list[list[str]]) -> dict[str, Any]:
    """Deduplicate many subdomain lists into one master list (SOP 1.6 data model)."""
    flat = [item for sub in lists for item in (sub or [])]
    master = sorted(utils.dedupe(flat))
    # persist for recon_report
    out = ctx.config.evidence_path("merge_assets") / "master-subdomains.txt"
    out.write_text("\n".join(master))
    ctx.auditor.record("merge_assets", {"lists": len(lists)}, None, "ok",
                       evidence_file=str(out), note=f"{len(master)} unique")
    return {"ok": True, "count": len(master), "subdomains": master,
            "evidence_file": str(out)}


def session_log(ctx: ReconContext, note: str) -> dict[str, Any]:
    ctx.auditor.record("session_log", {"note": note[:80]}, None, "ok", note=note)
    return {"ok": True, "logged": note}


def recon_report(ctx: ReconContext, engagement_id: str) -> dict[str, Any]:
    """Fill the SOP §4.3 report template from everything saved under the engagement."""
    base = ctx.config.evidence_dir / (engagement_id or ctx.config.engagement_id)
    if not base.exists():
        return {"ok": False, "error": f"no evidence directory for {engagement_id}"}

    # Gather what we can from the audit trail.
    audit = base / "audit.jsonl"
    tools_run: dict[str, int] = {}
    if audit.exists():
        for line in audit.read_text().splitlines():
            try:
                e = json.loads(line)
                tools_run[e["tool"]] = tools_run.get(e["tool"], 0) + 1
            except (json.JSONDecodeError, KeyError):
                continue
    master_sub = base / "merge_assets" / "master-subdomains.txt"
    assets = master_sub.read_text().splitlines() if master_sub.exists() else []
    s = ctx.config.scope

    md = f"""# Reconnaissance Report — {engagement_id}
_recon methodology §4.3 — generated by redpent-tools_

## 1. Scope
- Engagement: {engagement_id}
- RoE reference: {s.roe_reference}
- Tester: {s.tester}
- In-scope domains: {', '.join(s.in_scope_domains) or 'n/a'}
- In-scope CIDRs: {', '.join(s.in_scope_cidrs) or 'n/a'}
- Out of scope: {', '.join(s.out_of_scope) or 'n/a'}
- Active testing authorized: {s.active_allowed}

## 2. Assets discovered
- Unique subdomains: {len(assets)}
{chr(10).join('  - ' + a for a in assets[:200])}

## 3. Tooling executed (from audit trail)
{chr(10).join(f'- {t}: {n} run(s)' for t, n in sorted(tools_run.items())) or '- (none recorded)'}

## 4. Technology stack
_Populate from httpx_probe / tech_fingerprint evidence under {base}/._

## 5. Security posture
_Populate from http_headers, tls_scan, waf_detect, email_auth_check evidence._

## 6. Findings
_Rank by exploitability. Each finding needs manual verification._

## 7. Ranked attack surface
_Prioritized list of exposed services / endpoints for the next assessment phase._

---
_Evidence root: {base}_
_Full audit trail: {audit}_
"""
    report_path = base / "RECON-REPORT.md"
    report_path.write_text(md)
    ctx.auditor.record("recon_report", {"engagement_id": engagement_id}, None, "ok",
                       evidence_file=str(report_path))
    return {"ok": True, "report_file": str(report_path), "asset_count": len(assets),
            "tools_run": tools_run}
